create table if not exists people (
  id bigint generated by default as identity primary key,
  full_name text not null check (length(trim(full_name)) > 0),
  first_name text,
  last_name text,
  birthdate date,
  birthday_md text check (birthday_md is null or birthday_md ~ '^\d{2}-\d{2}$'),
  city text,
  country text,
  current_org text,
  "current_role" text,
  linkedin_url text,
  tie_strength smallint check (tie_strength between 1 and 5),
  met_where text,
  met_when text,
  summary text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists people_name_trgm_idx
  on people using gin (lower(full_name) extensions.gin_trgm_ops);
create index if not exists people_org_idx on people (current_org);
create index if not exists people_city_idx on people (city);

create table if not exists identifiers (
  person_id bigint not null references people(id) on delete cascade,
  kind text not null check (length(trim(kind)) > 0),
  value text not null check (length(trim(value)) > 0),
  is_primary boolean not null default false,
  source text not null default 'manual',
  observed_at date not null default current_date,
  primary key (kind, value)
);

create index if not exists identifiers_person_idx on identifiers(person_id);

create table if not exists orgs (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0),
  kind text,
  domain text,
  city text,
  country text,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists orgs_name_trgm_idx
  on orgs using gin (lower(name) extensions.gin_trgm_ops);

create table if not exists affiliations (
  person_id bigint not null references people(id) on delete cascade,
  org_id bigint not null references orgs(id) on delete cascade,
  role text not null default '',
  since date,
  until date,
  source text not null default 'manual',
  observed_at date not null default current_date,
  primary key (person_id, org_id, role),
  check (until is null or since is null or until >= since)
);

create index if not exists affiliations_org_idx on affiliations(org_id);

create table if not exists edges (
  a_id bigint not null references people(id) on delete cascade,
  b_id bigint not null references people(id) on delete cascade,
  kind text not null check (length(trim(kind)) > 0),
  strength smallint check (strength between 1 and 5),
  since date,
  until date,
  note text,
  source text not null default 'manual',
  observed_at date not null default current_date,
  primary key (a_id, b_id, kind),
  check (a_id <> b_id),
  check (until is null or since is null or until >= since)
);

create index if not exists edges_b_idx on edges(b_id, kind);

create or replace function canonicalize_symmetric_edge()
returns trigger
language plpgsql
as $$
declare
  original_a bigint;
begin
  if new.kind in (
    'friend', 'family', 'partner', 'colleague', 'knows', 'classmate',
    'sibling', 'neighbor', 'neighbour'
  ) and new.a_id > new.b_id then
    original_a := new.a_id;
    new.a_id := new.b_id;
    new.b_id := original_a;
  end if;
  return new;
end;
$$;

drop trigger if exists edges_canonicalize_symmetric on edges;
create trigger edges_canonicalize_symmetric
before insert or update of a_id, b_id, kind on edges
for each row execute function canonicalize_symmetric_edge();

create table if not exists facts (
  id bigint generated by default as identity primary key,
  person_id bigint not null references people(id) on delete cascade,
  key text not null check (length(trim(key)) > 0),
  value text,
  num double precision,
  date date,
  source text not null default 'manual',
  observed_at date not null default current_date,
  confidence text not null default 'stated'
    check (confidence in ('stated', 'observed', 'inferred')),
  created_at timestamptz not null default now()
);

create index if not exists facts_person_idx on facts(person_id);
create index if not exists facts_key_idx on facts(key);

